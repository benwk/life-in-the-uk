import Foundation
import Observation
import RobinCore

/// How bilingual text is shown (docs/product/07-language-experience.md).
enum LensMode: String, CaseIterable, Identifiable {
    case nativeFirst, sideBySide, englishFirst

    var id: String { rawValue }

    var label: String {
        switch self {
        case .nativeFirst: "Native first"
        case .sideBySide: "Side by side"
        case .englishFirst: "English first"
        }
    }
}

/// App-wide state: the content bundle plus the learner's settings and progress.
/// UserDefaults is enough for the skeleton; move to SwiftData once FSRS
/// review history is stored per fact.
@Observable
final class AppState {
    let bundle: ContentBundle

    /// Language used for translations, explanations and memory hooks.
    private(set) var learnerLocale: String
    private(set) var lensMode: LensMode
    private(set) var stamps: Set<String>
    private(set) var mistakes: Set<String>
    private(set) var seen: Set<String>

    @ObservationIgnored private let defaults = UserDefaults.standard

    init() {
        guard let url = Bundle.main.url(forResource: "content", withExtension: "json"),
              let data = try? Data(contentsOf: url),
              let bundle = try? ContentBundle.decode(data)
        else {
            fatalError("content.json missing or invalid; it is generated by tools/build_content.py during the build")
        }
        let defaults = UserDefaults.standard
        self.bundle = bundle
        learnerLocale = defaults.string(forKey: "learnerLocale") ?? "zh-Hans"
        lensMode = LensMode(rawValue: defaults.string(forKey: "lensMode") ?? "") ?? .sideBySide
        stamps = Set(defaults.stringArray(forKey: "stamps") ?? [])
        mistakes = Set(defaults.stringArray(forKey: "mistakes") ?? [])
        seen = Set(defaults.stringArray(forKey: "seen") ?? [])
    }

    func updateLearnerLocale(_ code: String) {
        learnerLocale = code
        defaults.set(code, forKey: "learnerLocale")
    }

    func updateLensMode(_ mode: LensMode) {
        lensMode = mode
        defaults.set(mode.rawValue, forKey: "lensMode")
    }

    func collectStamp(_ stationId: String) {
        stamps.insert(stationId)
        defaults.set(Array(stamps), forKey: "stamps")
    }

    func recordAnswer(_ questionId: String, correct: Bool) {
        seen.insert(questionId)
        if correct { mistakes.remove(questionId) } else { mistakes.insert(questionId) }
        defaults.set(Array(seen), forKey: "seen")
        defaults.set(Array(mistakes), forKey: "mistakes")
    }
}
